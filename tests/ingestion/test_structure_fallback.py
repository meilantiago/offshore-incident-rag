"""AC-002-07: a document whose structure is not recognized falls back to marked fixed windows and is not a failure.

The two unrecognized documents are generated by tests/support/pdfs.py: a district report without fields 17-24 and a
panel report with no Contents page and no headings.
"""

from __future__ import annotations

import re
from typing import Any

import pytest

from tests.conftest import migrate_schema
from tests.support import pdfs
from tests.support.ingest import EXIT_OK, IngestEnv, assert_exit, outcomes, run_cli
from tests.support.structure import (
    DISTRICT,
    FIXED,
    NO_REMOVAL,
    NOT_RECOGNIZED,
    SIZE_CAP,
    STRUCTURE,
    UNRECOGNIZED_DISTRICT,
    UNRECOGNIZED_PANEL,
    assert_tiles,
    chunk_pdf,
    chunk_rows,
    kept_words,
    serve_docs,
    set_strategies,
    words,
)

UNRECOGNIZED = [
    ("district_report", pdfs.district_without_fields_pdf),
    ("panel_report", pdfs.panel_without_headings_pdf),
]


def _assert_fallback(chunks: list[dict[str, Any]], pages: list[tuple[int, str, bool]], label: str) -> None:
    stream = kept_words(pages, NO_REMOVAL)  # every word of the text pages
    assert len(stream) > SIZE_CAP, f"{label}: fixture precondition: more than one window of text"
    assert chunks, f"{label}: no structure_aware chunk"
    labels = {c.get("section") for c in chunks}
    assert labels == {NOT_RECOGNIZED}, f"{label}: fallback chunks must all be labelled {NOT_RECOGNIZED}: {labels}"
    assert_tiles(chunks, stream, label)  # covers every word, no overlap, in order
    sizes = [len(words(c["text"])) for c in sorted(chunks, key=lambda c: c["ordinal"])]
    assert all(n == SIZE_CAP for n in sizes[:-1]) and 0 < sizes[-1] <= SIZE_CAP, (
        f"{label}: fallback windows are fixed windows of {SIZE_CAP} words with no overlap: {sizes}"
    )


@pytest.mark.parametrize(("doc_type", "make"), UNRECOGNIZED, ids=[t for t, _ in UNRECOGNIZED])
def test_ac_002_07_unrecognized_structure_falls_back_to_labelled_fixed_windows(doc_type: str, make: Any) -> None:
    """AC-002-07: fixed windows of at most 250 words, no overlap, every word covered, each `structure_not_recognized`."""
    chunks, pages = chunk_pdf(make(), doc_type)

    _assert_fallback(chunks, pages, doc_type)


def _not_recognized_entries(report: dict[str, Any]) -> list[dict[str, Any]]:
    keys = [k for k in report if re.search(r"not_?recognized", k, re.IGNORECASE)]
    assert len(keys) == 1, f"the ingestion report has no single structure-not-recognized list: {sorted(report)}"
    entries = report[keys[0]]
    assert isinstance(entries, list), f"report[{keys[0]!r}] is not a list"
    return entries


@pytest.mark.integration
def test_ac_002_07_ingest_stores_fallback_and_reports_it_without_failing(db_env: IngestEnv) -> None:
    """AC-002-07: ingest exits 0, stores fixed_words as usual, and the report lists the documents with URL and type."""
    migrate_schema(db_env.db)
    docs = serve_docs(db_env, [UNRECOGNIZED_DISTRICT, UNRECOGNIZED_PANEL, DISTRICT])
    set_strategies(db_env, [FIXED, STRUCTURE])

    run = db_env.ingest()

    assert_exit(run, EXIT_OK)
    report = db_env.latest_report()
    assert report["counts"]["failed"] == 0, "a document with no recognized structure is not a failure"
    listed = {e.get("source_url"): e for e in _not_recognized_entries(report)}
    for url, doc in docs.items():
        assert outcomes(report)[url]["status"] == "ingested"
        assert chunk_rows(db_env, url, FIXED), f"{doc.name}: fixed_words chunks are stored as usual"
        sa = chunk_rows(db_env, url, STRUCTURE)
        assert sa, f"{doc.name}: no structure_aware chunk"
        if doc.recognized:
            assert url not in listed, f"{doc.name} has a recognized structure and must not be listed"
            assert NOT_RECOGNIZED not in {c.get("section") for c in sa}
        else:
            assert url in listed, f"{doc.name} is not listed under structure not recognized: {sorted(listed)}"
            assert listed[url].get("doc_type") == doc.doc_type, f"{doc.name}: the listing names its document type"
            _assert_fallback(sa, db_env.pages(url), doc.name)


@pytest.mark.integration
def test_ac_002_07_rechunk_stores_fallback_without_failing(db_env: IngestEnv) -> None:
    """AC-002-07: re-chunking a stored unrecognized document gives the same marked fallback and exits 0."""
    migrate_schema(db_env.db)
    docs = serve_docs(db_env, [UNRECOGNIZED_DISTRICT, UNRECOGNIZED_PANEL])
    assert_exit(db_env.ingest(), EXIT_OK)
    set_strategies(db_env, [FIXED, STRUCTURE])

    run = run_cli("rechunk")

    assert_exit(run, EXIT_OK)
    for url, doc in docs.items():
        _assert_fallback(chunk_rows(db_env, url, STRUCTURE), db_env.pages(url), doc.name)
        assert url in run.stdout, f"the rechunk summary lists {doc.name} as structure not recognized"
